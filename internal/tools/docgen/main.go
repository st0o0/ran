// Command docgen writes docs/traps.generated.md, the trap overview table of
// the documentation site, from config.DefaultPorts and config.AddresslessTraps.
//
// Usage (from the repository root):
//
//	go run ./internal/tools/docgen
//
// An optional argument names the output file.
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/st0o0/ran/internal/config"
)

const defaultOut = "docs/traps.generated.md"

// udpTraps lists the traps that speak UDP; every other trap is TCP. UDP traps
// never raise CrowdSec alerts.
var udpTraps = map[string]bool{"dns": true, "snmp": true, "sip": true, "ntp": true}

func transport(name string) string {
	if udpTraps[name] {
		return "UDP"
	}
	return "TCP"
}

// render returns the Markdown table: sorted by trap name, LF line endings.
func render() string {
	var names []string
	for n := range config.DefaultPorts {
		names = append(names, n)
	}
	for n := range config.AddresslessTraps {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("<!-- Generated by `go run ./internal/tools/docgen` from config.DefaultPorts and config.AddresslessTraps. Do not edit. -->\n\n")
	b.WriteString("## Overview\n\n")
	b.WriteString("| Trap | Default listen address | Transport | Address variable |\n")
	b.WriteString("|---|---|---|---|\n")
	for _, n := range names {
		if ports, ok := config.DefaultPorts[n]; ok {
			parts := strings.Split(ports, ",")
			for i, p := range parts {
				parts[i] = "`" + strings.TrimSpace(p) + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | `RAN_%s_ADDR` |\n", n, strings.Join(parts, ", "), transport(n), strings.ToUpper(n))
			continue
		}
		fmt.Fprintf(&b, "| `%s` | none (required) | %s | `%s` |\n", n, transport(n), config.AddresslessTraps[n])
	}
	return b.String()
}

func main() {
	out := defaultOut
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	if err := os.WriteFile(out, []byte(render()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}
